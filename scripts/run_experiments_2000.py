#!/usr/bin/env python3
"""
Main script to run 2000-evaluation experiments, compute profiles, and generate plots.
"""

import sys
import os
import pandas as pd

# Add parent directory to path to import experiments package
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

from experiments.experiment_runner_2000 import run_experiments
from experiments.profiles import (
    compute_best_known_value,
    compute_success,
    build_data_profile_evals,
    build_data_profile_time
)
# Plots are generated separately by regenerate_profiles_tau.py
from experiments.config_2000 import MAX_EVALS, EVAL_BUDGET_STEP, MAX_CPU_TIME


def main():
    """Run complete experimental pipeline with MAX_EVALS = 2000."""
    print("=" * 60)
    print("Coordinate Search Variants Benchmark on SOLAR10 (2000 evals)")
    print("=" * 60)
    
    # Create results directory if it doesn't exist
    results_dir = os.path.join(os.path.dirname(os.path.dirname(__file__)), 'results')
    plots_dir = os.path.join(results_dir, 'plots')
    os.makedirs(results_dir, exist_ok=True)
    os.makedirs(plots_dir, exist_ok=True)
    
    # Step 1: Run experiments
    print("\n[1/5] Running experiments (MAX_EVALS = 2000)...")
    df = run_experiments()
    print(f"   Completed {len(df)} runs across {df['instance_id'].nunique()} instances")
    
    # Step 2: Compute best-known value
    print("\n[2/5] Computing best-known value...")
    f_star = compute_best_known_value(df)
    print(f"   f* = {f_star:.6e}")
    
    # Step 3: Add success column
    print("\n[3/5] Computing success criterion...")
    df['success'] = compute_success(df, f_star)
    success_rate = df['success'].mean()
    print(f"   Overall success rate: {success_rate:.2%}")
    
    # Step 4: Build data profiles
    print("\n[4/5] Building data profiles...")
    profile_evals = build_data_profile_evals(df, f_star, max_evals=MAX_EVALS, eval_budget_step=EVAL_BUDGET_STEP)
    profile_time = build_data_profile_time(df, f_star)
    print("   Data profiles computed")
    
    # Step 5: Save results
    print("\n[5/5] Saving results...")
    
    # Save raw runs
    raw_runs_path = os.path.join(results_dir, 'raw_runs_2000.csv')
    df.to_csv(raw_runs_path, index=False)
    print(f"   Saved: {raw_runs_path}")
    
    # Save raw runs with success column
    raw_runs_success_path = os.path.join(results_dir, 'raw_runs_with_success_2000.csv')
    df.to_csv(raw_runs_success_path, index=False)
    print(f"   Saved: {raw_runs_success_path}")
    
    # Save data profiles
    profile_evals_path = os.path.join(results_dir, 'data_profiles_eval_2000.csv')
    profile_time_path = os.path.join(results_dir, 'data_profiles_time_2000.csv')
    profile_evals.to_csv(profile_evals_path, index=False)
    profile_time.to_csv(profile_time_path, index=False)
    print(f"   Saved: {profile_evals_path}")
    print(f"   Saved: {profile_time_path}")
    
    # Note: Plots are generated by regenerate_profiles_tau.py script
    # This script only generates data files
    
    # Print summary statistics
    print("\n" + "=" * 60)
    print("Summary Statistics")
    print("=" * 60)
    print(f"\nBest-known value (f*): {f_star:.6e}")
    print(f"\nSuccess rates by algorithm:")
    for algo in ['Complete', 'Ordered', 'Opportunistic']:
        algo_df = df[df['algo'] == algo]
        algo_success = algo_df['success'].mean()
        print(f"  {algo:15s}: {algo_success:.2%}")
    
    print(f"\nAverage evaluations by algorithm:")
    for algo in ['Complete', 'Ordered', 'Opportunistic']:
        algo_df = df[df['algo'] == algo]
        avg_evals = algo_df['evals'].mean()
        print(f"  {algo:15s}: {avg_evals:.1f}")
    
    print(f"\nAverage CPU time by algorithm:")
    for algo in ['Complete', 'Ordered', 'Opportunistic']:
        algo_df = df[df['algo'] == algo]
        avg_time = algo_df['cpu_time'].mean()
        print(f"  {algo:15s}: {avg_time:.4f} seconds")
    
    print("\n" + "=" * 60)
    print("All results saved to:", results_dir)
    print("=" * 60)


if __name__ == '__main__':
    main()

